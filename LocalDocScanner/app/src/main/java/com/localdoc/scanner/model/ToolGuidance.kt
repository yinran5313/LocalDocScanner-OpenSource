package com.localdoc.scanner.model

data class ToolGuidance(val purpose: String, val steps: List<String>) {
    val text get()=purpose+"\n\n"+steps.mapIndexed { index,step -> "${index+1}. $step" }.joinToString("\n")
}

fun toolGuidance(tool: ToolEntry): ToolGuidance {
    val (purpose,flow)=when(tool.id) {
        "pdf_sign" -> "用自己的证书校验PDF完整性；与手写签名不同。" to "选择PDF→导入含私钥的P12/PFX证书并输入密码→核对证书、名称和说明→生成签名副本并保存"
        "batch_extract" -> "将多张票据的商户、日期和金额汇总为表格，离线识别不等于验真。" to "选择票据图片或PDF→选择发票或收据并识别→逐份对照原图，修正字段并确认→生成XLSX，预览后保存或分享"
        "table_xlsx" -> "把纸面表格恢复为可复核的行列，原图不存在的公式不会恢复。" to "选择表格图片或PDF→识别；可启用已安装的结构模型→核对原图、行列、合并格和列类型→生成XLSX并保存"
        "pdf_office" -> "在PDF副本上填写、标记、签名或打码。" to "在画布选择页面和底部工具→打开参数填写内容，拖框移动或缩放→多项修改先加入编辑清单→生成副本，在真实预览中核对并保存"
        "pdf_pages" -> "用缩略图整理PDF页序、方向及保留范围。" to "选择PDF→选中页面后排序、旋转或删除→核对选页数量与次序→生成新PDF并保存"
        "pdf_merge", "image_ppt" -> "按指定顺序组合文件，每张图片可成为一页演示。" to "选择多份文件→调整顺序→生成并检查页数与内容→保存或分享副本"
        "pdf_split" -> "按页码范围拆分PDF。" to "选择PDF→填写要保留的页码范围→生成并逐份预览→保存或分享所需文件"
        "pdf_compress" -> "通过重采样降低PDF体积，请核对小字和印章清晰度。" to "选择PDF→设置压缩质量→生成后比较清晰度和大小→保存压缩副本"
        "pdf_to_images", "pdf_long" -> "把PDF选页导出为图片；长图过高时分块输出。" to "选择PDF→输入页码并核对范围→设置图片质量或分块高度→生成、预览并保存图片"
        "pdf_text" -> "提取PDF已有文字层；扫描图片可改用文字识别。" to "选择PDF→提取文字→核对并复制内容→保存或分享文字文件"
        "pdf_encrypt" -> "给PDF副本设置打开密码。" to "选择PDF→输入并记住密码→生成后尝试重新打开→保存加密副本"
        "pdf_compare" -> "逐页比较两份PDF的视觉差异。" to "依次选择两份PDF→设置比较选项→查看差异结果→保存对照文件"
        "pdf_enhance" -> "逐页增强扫描PDF，原件保留；表单和批注不迁移。" to "选PDF并指定页码→设置增强和可选高清模型→对照增强前后小字→保存新PDF"
        "ocr", "card" -> "使用内置medium识别文字，重要字段需人工复核。" to "选择清晰图片或PDF→设置语言或证件类型→对照原图修正文字和字段→保存文字、PDF或证件副本"
        "translate" -> "先识别图片文字，再用已安装的本地翻译模型翻译。" to "选择图片→确认翻译方向和模型→核对原文并校订译文→保存或分享译文"
        "structured_markdown" -> "保留原图区域，按版面整理为Markdown。" to "选择图片或PDF→选择版面、表格及分栏选项→核对文字、表格与插图→保存完整ZIP以保留图片引用"
        "formula" -> "把公式图片识别为可校订的表达式。" to "选择公式图片→确认公式模型已安装→识别后对照原图修改→复制或保存表达式"
        "photo_restore" -> "本地高清、去模糊或降噪，不能保证恢复丢失的真实文字。" to "选择照片→选择模式并确认所需模型→对照原图检查细节→保存修复副本"
        "book_unwarp" -> "对书页照片做双页拆分和曲面展平。" to "选择书页照片→设置拆分与展平→对照书缝文字和页边→保存展平副本"
        "portrait" -> "本地抠出人物并更换证件照背景。" to "选择人像→选择背景及尺寸→核对发丝和边缘→保存PNG或证件照副本"
        "region_erase" -> "修补选定区域背景，请避开需要保留的文字。" to "选择图片→框选需要修补的位置→生成预览并对照原图→满意后保存副本"
        "count_objects" -> "识别常见物体并允许人工补点或删除误检。" to "选择照片并运行检测→选择需要计数的类别→在原图补点或删除错误标记→核对总数并保存结果"
        "qr_create" -> "将文本或链接生成二维码。" to "输入内容→选择尺寸并生成→核对二维码内容与预览→保存图片或分享"
        "barcode", "barcode_live" -> "识别条码与二维码，链接由你决定是否打开。" to "选图或实时扫描→核对识别到的文本与类型→按需复制、保存或打开链接→在历史记录中重新查看"
        "long_image", "images_to_pdf", "image_edit" -> "整理图片并生成可预览的独立副本。" to "选择图片→调整顺序、裁边或增强选项→生成并核对预览→保存或分享结果"
        "watermark_photo", "watermark_camera" -> "在照片上记录时间与可选的本地定位信息。" to "拍摄或选择照片→确认时间和位置，位置可留空→核对水印预览→保存照片副本"
        "zip_import" -> "检查压缩包内容后，选择保存或加入文档库。" to "选择ZIP→解压并检查文件→核对目录与文件名→保存或导入文档库"
        "sign_library" -> "保存常用签名，后续放置到PDF副本。" to "新建手写或导入图片→裁切并命名→保存到本机签名库→在PDF图片签名中复用"
        "card_wallet" -> "把证件副本按类型整理在本机。" to "扫描或导入证件→复核证件类型和字段→保存到卡包→从卡包打开、整理或分享副本"
        else -> "${tool.label}：按下列步骤完成并核对结果。" to "${if(tool.accept==FileKind.NONE) "打开工具并输入内容" else "选择需要处理的文件"}→调整本次处理选项→核对真实结果→保存或分享副本"
    }
    return ToolGuidance(purpose,flow.split('→'))
}
